"""Archive the exact acceptance source and existing read-only runtime identities."""
import argparse
from datetime import datetime, timezone
import hashlib
import importlib.metadata
import json
from pathlib import Path
import zipfile
import psutil
from scripts.campaign9_manager.integrity import dependencies
from scripts.campaign10_manager.admission import original_model_admission
from scripts.campaign10_verification.integrity import snapshot_source, assert_freeze, digest
ROOT = Path(__file__).resolve().parents[2]
OWNED = ROOT / 'data/campaign10-manager'

def write(path, value):
    with path.open('x', encoding='utf8') as handle:
        json.dump(value, handle, indent=2, allow_nan=False)
        handle.write('\n')

def file_identity(path):
    path = Path(path).resolve()
    before = path.stat()
    hasher = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b''):
            hasher.update(block)
    after = path.stat()
    if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
        raise RuntimeError('An existing runtime file changed during read-only hashing.')
    return {'path': str(path), 'size': after.st_size, 'mtime_ns': after.st_mtime_ns, 'sha256': hasher.hexdigest()}

def dependency_identity():
    """Hash all installed distribution files, except generated bytecode/cache."""
    rows = []
    hashed = {}
    for distribution in importlib.metadata.distributions():
        files = {}
        for relative in distribution.files or ():
            path = Path(distribution.locate_file(relative)).resolve()
            if path.suffix == '.pyc' or '__pycache__' in path.parts or (not path.is_file()):
                continue
            key = str(path)
            if key not in hashed:
                identity = file_identity(path)
                hashed[key] = {field: identity[field] for field in ('size', 'sha256')}
            files[key] = hashed[key]
        rows.append({'name': distribution.metadata['Name'], 'version': distribution.version, 'installed_file_hashes': dict(sorted(files.items()))})
    rows.sort(key=lambda row: (row['name'].casefold(), row['version'], tuple(row['installed_file_hashes'])))
    return {'protocol_python_stdlib': dependencies(), 'installed_distributions': rows, 'scope': 'All discoverable installed distribution files and the original Python/protocol/stdlib drivers; generated bytecode/cache excluded.'}

def seal(out):
    out = Path(out).resolve()
    if out == OWNED or not out.is_relative_to(OWNED) or out.exists():
        raise ValueError('A fresh acceptance-owned checkpoint directory is required.')
    out.mkdir(parents=True, exist_ok=False)
    admission = original_model_admission()
    freeze = snapshot_source(ROOT)
    write(out / 'SOURCE_MANIFEST.json', freeze)
    write(out / 'DEPENDENCIES.json', dependency_identity())
    write(out / 'ADMISSION.json', admission)
    files = {'native': file_identity(ROOT / 'dist/HANNI OS/HANNI OS.exe'), 'weights': file_identity(admission['process']['model_path']), 'server': file_identity(psutil.Process(admission['process']['pid']).exe())}
    write(out / 'RUNTIME_FILES.json', files)
    with zipfile.ZipFile(out / 'SOURCE.zip', 'x', zipfile.ZIP_DEFLATED) as archive:
        for row in freeze['files']:
            archive.write(ROOT / row['path'], row['path'])
    assert_freeze(ROOT, freeze)
    original_model_admission(admission['process'])
    write(out / 'CHECKPOINT.json', {'at': datetime.now(timezone.utc).isoformat(), 'state': 'FROZEN_BEFORE_FINAL_GO', 'source_sha256': freeze['source_sha256'], 'source_files': freeze['file_count'], 'archive_sha256': digest(out / 'SOURCE.zip'), 'dependencies_sha256': digest(out / 'DEPENDENCIES.json'), 'runtime_files_sha256': digest(out / 'RUNTIME_FILES.json'), 'private_inputs_or_answers_read': False, 'final_go_issued': False, 'owner_databases_read_or_mounted': False})
    return {'source_sha256': freeze['source_sha256'], 'source_files': freeze['file_count'], 'out': out.relative_to(ROOT).as_posix()}

def verify(frozen, output):
    frozen = Path(frozen).resolve()
    if frozen == OWNED or not frozen.is_relative_to(OWNED):
        raise ValueError('Only an acceptance-owned freeze can be verified.')
    output = Path(output).resolve()
    if output == OWNED or not output.is_relative_to(OWNED):
        raise ValueError('Verification output must be acceptance-owned.')
    manifest = json.loads((frozen / 'SOURCE_MANIFEST.json').read_text(encoding='utf8'))
    source_hash = assert_freeze(ROOT, manifest)
    unchanged = dependency_identity() == json.loads((frozen / 'DEPENDENCIES.json').read_text(encoding='utf8'))
    checkpoint = json.loads((frozen / 'CHECKPOINT.json').read_text(encoding='utf8'))
    archive_unchanged = digest(frozen / 'SOURCE.zip') == checkpoint['archive_sha256']
    receipt_pins_unchanged = digest(frozen / 'DEPENDENCIES.json') == checkpoint['dependencies_sha256'] and digest(frozen / 'RUNTIME_FILES.json') == checkpoint['runtime_files_sha256']
    expected = json.loads((frozen / 'RUNTIME_FILES.json').read_text(encoding='utf8'))
    current = {name: file_identity(row['path']) for name, row in expected.items()}
    receipt = {'at': datetime.now(timezone.utc).isoformat(), 'source_sha256': source_hash, 'dependencies_unchanged': unchanged, 'runtime_files_unchanged': current == expected, 'archive_unchanged': archive_unchanged, 'dependency_runtime_receipt_pins_unchanged': receipt_pins_unchanged, 'private_inputs_or_answers_read': False}
    write(output, receipt)
    if not unchanged or current != expected or (not archive_unchanged) or (not receipt_pins_unchanged):
        raise RuntimeError('Frozen dependencies or runtime files changed; retain the evidence.')
    return receipt
if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['seal', 'verify'])
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--frozen', type=Path)
    args = parser.parse_args()
    print(json.dumps(seal(args.out) if args.action == 'seal' else verify(args.frozen, args.out)))
